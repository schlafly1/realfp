#!/usr/bin/env python3
"""Generate Lean files for a big split certificate (docs/GPU.md, "Very large certificates").

usage: gen_lean.py PROBLEM SPLITCERT OUTDIR MODULE [--groups K1]

  PROBLEM    the problem file written by `interval_grid (export := "P.problem")`; its Lean
             source P.problem.lean.txt (same directory) gives e, bs, c
  SPLITCERT  `realfp-grid prove P.problem -o S --split K` (or `realfp-grid split ...`)
  OUTDIR     directory for the generated modules, inside a Lean library's source tree
  MODULE     the module name of OUTDIR, e.g. RealFPGridShowcase.R8
  --groups K1  group the sub-checks by the top tree's depth-K1 subtrees (default: about 16 per file)

Generated (everything is checked by Lean; nothing here is trusted):
  OUTDIR/Problem.lean  e, bs, c, the box bits env0 (Mathlib-free)
  OUTDIR/Gnnn.lean     one group of sub-checks: `ok` by native_decide (the C checker), then
                       `sound : checkC2 ... (top.toCert d env) env = true` by `Top.sound` (Mathlib-free)
  OUTDIR/hex/jN.hex    the sub-certificates (read at elaboration time by `grid_hex%`)
  OUTDIR/Main.lean     `TopC.sound` over the groups + `proveTopC_le/ge`: theorem `bound`
                       (`∀ xs, InBoxes xs bs → e.denote xs ≤ c`, Mathlib); close a goal with
                       `interval_grid (use := MODULE.bound)` (namespaced as MODULE).
The groups are independent Lean modules, so `lake build` checks them in parallel (set
RFG_THREADS=1 so that each process's C checker uses one thread)."""
import os, sys, struct, re

def f2b(x): return struct.unpack('<Q', struct.pack('<d', x))[0]
def b2f(n): return struct.unpack('<d', struct.pack('<Q', n))[0]
def midF(lo, hi): return lo * 0.5 + hi * 0.5        # binary64 round-to-nearest, as the checker

def main():
    a = sys.argv[1:]
    if len(a) < 4: print(__doc__); sys.exit(2)
    prob, splitc, outdir, module = a[:4]
    K1 = None
    if '--groups' in a: K1 = int(a[a.index('--groups') + 1])
    # problem: box bits, goal
    toks = []
    for l in open(prob):
        if not l.startswith('#'): toks += l.split()
    assert toks[0] == 'realfp-grid-problem'
    d = int(toks[3]); box = []
    for j in range(d):
        assert toks[4 + 3 * j] == 'box'
        box.append((int(toks[5 + 3 * j], 16), int(toks[6 + 3 * j], 16)))
    upper = toks[4 + 3 * d + 1] == 'le'
    src = {}
    for l in open(prob + '.lean.txt'):
        if l.startswith('--'): continue
        k, _, v = l.partition(' : ')
        src[k.strip()] = v.strip()
    # split certificate
    top = None; jobs = []
    for l in open(splitc):
        if l.startswith('#') or not l.strip(): continue
        t = l.split()
        if t[0] == 'top': top = t[1]
        elif t[0] == 'job': jobs.append((int(t[1]), t[2]))
    bits = ''.join(f"{int(ch, 16):04b}" for ch in top)
    # parse the top tree: nodes ('S', i, m, L, R, depth, env) / ('J', k, depth, env)
    pos = [0]; jk = [0]
    def parse(l, env):
        b = bits[pos[0]]; pos[0] += 1
        if b == '0':
            k = jk[0]; jk[0] += 1
            assert jobs[k][0] == l, (jobs[k][0], l)
            return ('J', k, l, env)
        i = l % d
        lo, hi = b2f(env[i][0]), b2f(env[i][1])
        m = f2b(midF(lo, hi))
        le = list(env); le[i] = (env[i][0], m)
        re_ = list(env); re_[i] = (m, env[i][1])
        return ('S', i, m, parse(l + 1, le), parse(l + 1, re_), l, env)
    tree = parse(0, box)
    assert jk[0] == len(jobs)
    maxd = max(j[0] for j in jobs)
    if K1 is None:
        K1 = max(0, maxd - 4)
    os.makedirs(os.path.join(outdir, 'hex'), exist_ok=True)
    ns = module
    kenv = lambda env: '[' + ', '.join(f'⟨{lo}, {hi}⟩' for lo, hi in env) + ']'
    cb = f"(KI.ofRat c).{'lo' if upper else 'hi'}"
    # Problem.lean
    with open(os.path.join(outdir, 'Problem.lean'), 'w') as f:
        f.write(f"import RealFPGridNative\n\n/-! Generated by grid/gen_lean.py from {os.path.basename(prob)}. -/\n\n")
        f.write(f"open Interval64 Interval64.KF RealFP.Grid\n\nnamespace {ns}\n\n")
        f.write(f"def e : IExpr := {src['e']}\n\ndef bs : List (Rat × Rat) := {src['bs']}\n\ndef c : Rat := {src['c']}\n\n")
        f.write(f"def env0 : List KI := {kenv(box)}\n\ntheorem env0_eq : boxes bs = env0 := by decide +kernel\n\n")
        f.write(f"def cb : Nat := {cb}\n\nend {ns}\n")
    # groups
    groups = []
    def collect(n):
        depth = n[5] if n[0] == 'S' else n[2]
        if n[0] == 'J' or depth == K1: groups.append(n); return
        collect(n[3]); collect(n[4])
    collect(tree)
    gname = {id(g): f"G{gi:03d}" if len(groups) <= 1000 else f"G{gi:05d}" for gi, g in enumerate(groups)}
    def topterm(n):
        if n[0] == 'J': return f'(.sub {jobs[n[1]][0]} h{n[1]})'
        return f'(.split {n[1]} {n[2]} {topterm(n[3])} {topterm(n[4])})'
    def jobsof(n, acc):
        if n[0] == 'J': acc.append(n); return acc
        jobsof(n[3], acc); jobsof(n[4], acc); return acc
    for g in groups:
        G = gname[id(g)]; js = jobsof(g, [])
        genv = g[3] if g[0] == 'J' else g[6]
        with open(os.path.join(outdir, f'{G}.lean'), 'w') as f:
            f.write(f"import {module}.Problem\n\n/-! Generated by grid/gen_lean.py: sub-checks {js[0][1]}..{js[-1][1]}. -/\n\n")
            f.write(f"open Interval64 Interval64.KF RealFP.Grid\nset_option maxRecDepth 100000\n\nnamespace {ns}.{G}\n\n")
            for n in js:
                k = n[1]
                with open(os.path.join(outdir, 'hex', f'j{k}.hex'), 'w') as h: h.write(jobs[k][1] + '\n')
                f.write(f'def h{k} : String := grid_hex% "hex/j{k}.hex"\n')
            f.write(f"\ndef env : List KI := {kenv(genv)}\n\n")
            f.write(f"def top : Top := {topterm(g)}\n\n")
            items = ',\n  '.join(f'⟨{jobs[n[1]][0]}, h{n[1]}, {kenv(n[3])}⟩' for n in js)
            f.write(f"def jobs : List Job := [\n  {items}]\n\n")
            f.write("theorem jobs_eq : top.jobs env = jobs := rfl\n\n")
            f.write("theorem midsOK : top.midsOK = true := by decide +kernel\n\n")
            f.write(f"theorem ok : jobs.all (Job.check (compile e) {str(upper).lower()} cb {d}) = true := by\n  native_decide\n\n")
            f.write(f"def cert : Cert := top.toCert {d} env\n\n")
            f.write(f"theorem sound : checkC2 (compile e) (if {str(upper).lower()} then gLe cb else gGe cb) cert env = true :=\n")
            f.write(f"  Top.sound _ _ _ _ top env midsOK (by rw [jobs_eq]; exact ok)\n\nend {ns}.{G}\n")
    # Main.lean
    def topc(n):
        depth = n[5] if n[0] == 'S' else n[2]
        if n[0] == 'J' or depth == K1: return f'(.leaf {gname[id(n)]}.cert)'
        return f'(.split {n[1]} {n[2]} {topc(n[3])} {topc(n[4])})'
    with open(os.path.join(outdir, 'Main.lean'), 'w') as f:
        f.write("import RealFPGrid\n")
        for g in groups: f.write(f"import {module}.{gname[id(g)]}\n")
        f.write(f"\n/-! Generated by grid/gen_lean.py: {len(jobs)} sub-checks in {len(groups)} files. -/\n\n")
        f.write(f"open Interval64 Interval64.KF RealFP.Grid\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\nnamespace {ns}\n\n")
        f.write(f"def topC : TopC := {topc(tree)}\n\n")
        f.write("theorem topC_midsOK : topC.midsOK = true := by decide +kernel\n\n")
        lv = ', '.join(f'({gname[id(g)]}.cert, {gname[id(g)]}.env)' for g in groups)
        f.write(f"theorem leaves_eq : topC.leaves env0 = [{lv}] := rfl\n\n")
        rel = "e.denote xs ≤ (c : ℝ)" if upper else "(c : ℝ) ≤ e.denote xs"
        sounds = ', '.join(f'{gname[id(g)]}.sound' for g in groups)
        f.write(f"/-- The bound on the whole box, from {len(jobs)} sub-checks in {len(groups)} files. -/\n")
        f.write(f"theorem bound (xs : List ℝ) (hxs : RealFP.InBoxes xs bs) : {rel} :=\n")
        f.write(f"  proveTopC_{'le' if upper else 'ge'} e bs c topC topC_midsOK\n")
        f.write(f"    (by rw [env0_eq, leaves_eq]; exact ⟨{sounds}, trivial⟩) xs hxs\n\nend {ns}\n")
    print(f"{len(jobs)} sub-checks in {len(groups)} group files (group depth {K1}, max job depth {maxd}); wrote {outdir}")

main()
