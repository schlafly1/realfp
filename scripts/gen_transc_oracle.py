#!/usr/bin/env python3
"""Generate tests/transc_oracle.txt: correctly rounded RD/RU exp, log, sin, cos
of special and random doubles, computed with mpmath (2500-bit working precision,
enough for subnormal results and tiny arguments).

    python3 scripts/gen_transc_oracle.py SEED COUNT > tests/transc_oracle.txt
"""
import random, struct, mpmath, math, sys
mpmath.mp.prec = 2500
def f2u(x): return struct.unpack('<Q',struct.pack('<d',x))[0]
def u2f(u): return struct.unpack('<d',struct.pack('<Q',u))[0]
random.seed(int(sys.argv[1]) if len(sys.argv)>1 else 1)
ins=[]
for fn in ['exp','log','sin','cos']:
  xs=[0.0,-0.0,1.0,-1.0,float('inf'),-float('inf'),float('nan'),5e-324,-5e-324,2.2250738585072014e-308,1.7976931348623157e308,-1.7976931348623157e308,709.78,709.79,710.0,-745.1,-745.2,-746.0,1e-300,-1e-300,0.5,2.0,3.0, 1e22, 1e300, float.fromhex('0x1p-1022')]
  for _ in range(int(sys.argv[2]) if len(sys.argv)>2 else 4000):
    r=random.random()
    if r<0.5: x=random.uniform(-750,750) if fn=='exp' else random.uniform(-10,10)
    elif r<0.7: x=random.uniform(-1,1)*2**random.randint(-60,4)
    else: x=u2f(random.getrandbits(64))
    if fn=='log' and random.random()<0.6: x=abs(x)
    xs.append(x)
  for x in xs: ins.append((fn,x))
def oracle(fn,x):
  if math.isnan(x): return None
  X=mpmath.mpf(x)
  if fn=='exp':
    if x==math.inf: return (math.inf,math.inf)
    if x==-math.inf: return (0.0,0.0)
    if x==0: return (1.0,1.0)
    y=mpmath.exp(X)
  elif fn=='log':
    if x<0 or (x==-math.inf): return None
    if x==0: return (-math.inf,-math.inf)
    if x==math.inf: return (math.inf,math.inf)
    if x==1: return (0.0,0.0)
    y=mpmath.log(X)
  elif fn=='sin':
    if math.isinf(x): return None
    if x==0: return (x,x)
    y=mpmath.sin(X)
  else:
    if math.isinf(x): return None
    if x==0: return (1.0,1.0)
    y=mpmath.cos(X)
  try: f=float(y)
  except OverflowError: f=math.inf if y>0 else -math.inf
  F=mpmath.mpf(f) if not math.isinf(f) else None
  if F is None:
    if f>0: return (1.7976931348623157e308, math.inf)
    else: return (-math.inf, -1.7976931348623157e308)
  if F==y: return (f,f)
  if F>y: return (math.nextafter(f,-math.inf), f)
  return (f, math.nextafter(f,math.inf))
print("# Oracle for CORE-MATH under RD/RU: fn input_bits RD_bits RU_bits (nan = NaN expected).")
print(f"# Generated by scripts/gen_transc_oracle.py with mpmath at {mpmath.mp.prec} bits; args: {' '.join(sys.argv[1:])}")
for fn,x in ins:
  o=oracle(fn,x)
  print(f"{fn} {f2u(x):016x} " + ("nan nan" if o is None else f"{f2u(o[0]):016x} {f2u(o[1]):016x}"))
