#!/usr/bin/env python3
"""Generate Lean files for a split certificate (output of `mb2 split`).

usage: gen_split.py CERTDIR NAME EXPR UPPER BOUND NFILES [THM_STATEMENT_FILE]
  CERTDIR  directory with top.txt + jobNNNNN.cert (path relative to lean/split/NAME/ is computed)
  NAME     Lean module directory name (split/NAME/S00.lean ... Main.lean)
  EXPR     Lean IExpr name (e.g. V2.eR8), UPPER true|false, BOUND a Lean rational (e.g. -12)
  NFILES   number of sub-files (jobs are dealt round-robin by size into NFILES groups)

Sub-files import only the Mathlib-free checker (ManyBoxTape, ManyBoxProbs); each proves
`jobs.all (Job.check (compile EXPR) UPPER c D) = true` by native_decide.  Main.lean builds the
`Top` term, checks `midsOK` and the job list by kernel computation / rfl, and applies
`proveTop_le/ge` (ManyBoxCert, Mathlib)."""
import os, sys
certdir, name, expr, upper, bound, nfiles = sys.argv[1:7]
nfiles = int(nfiles)
here = os.path.dirname(os.path.abspath(__file__))
outdir = os.path.join(here, name)
os.makedirs(outdir, exist_ok=True)
rel = os.path.relpath(os.path.abspath(certdir), outdir)
lines = [l.split() for l in open(os.path.join(certdir, 'top.txt')) if l.strip() and not l.startswith('#')]
hdr = open(os.path.join(certdir, 'top.txt')).readline().strip()
d = int(hdr.split(' dim ')[1].split()[0])
LO, HI = 0xBFF0000000000000, 0x3FF0000000000000
pos = 0
jobs = []  # (l0, cs0, file, env)
def parse(env):
    global pos
    t = lines[pos]; pos += 1
    if t[0] == 'S':
        i, m = int(t[1]), int(t[2])
        lenv = list(env); lenv[i] = (env[i][0], m)
        renv = list(env); renv[i] = (m, env[i][1])
        l = parse(lenv); r = parse(renv)
        return f".split {i} {m}\n ({l})\n ({r})"
    l0 = int(t[1]); cs0 = [int(x) for x in t[2:2 + d]]; fn = t[2 + d]
    k = len(jobs); jobs.append((l0, cs0, fn, env))
    return f".sub {l0} {cs0} @@{k}@@"
topterm = parse([(LO, HI)] * d)
assert pos == len(lines)
ub = upper == 'true'
cexpr = f"(KI.ofRat ({bound})).{'lo' if ub else 'hi'}"
ns = f"ManyBox.Split.{name}"
# contiguous groups (in Top order) of roughly equal certificate size
size = [1 + (os.path.getsize(os.path.join(certdir, j[2])) if j[2] != '0' else 0) for j in jobs]
tot = sum(size); grp = []; acc = 0
for k in range(len(jobs)):
    grp.append(min(nfiles - 1, acc * nfiles // tot)); acc += size[k]
groups = sorted(set(grp))
gname = {g: f"G{i:02d}" for i, g in enumerate(groups)}
for g in groups:
    mine = [k for k in range(len(jobs)) if grp[k] == g]; G = gname[g]
    with open(os.path.join(outdir, f"{G}.lean"), 'w') as f:
        f.write("import ManyBoxTape\nimport ManyBoxProbs\nopen Interval64.KF ManyBox\nset_option profiler true\nset_option profiler.threshold 200\n\n")
        f.write(f"/-! Sub-checks {mine[0]}..{mine[-1]} of split certificate `{name}` (generated by gen_split.py). -/\n\n")
        f.write(f"namespace {ns}.{G}\n\n")
        for k in mine:
            if jobs[k][2] != '0':
                f.write(f'def h{k} : String := mb_hex% "{rel}/{jobs[k][2]}"\n')
        items = []
        for k in mine:
            l0, cs0, fn, env = jobs[k]
            hx = '"0"' if fn == '0' else f"h{k}"
            envs = ", ".join(f"⟨{a}, {b}⟩" for a, b in env)
            items.append(f"  ⟨{l0}, {cs0}, {hx}, [{envs}]⟩")
        f.write("\ndef jobs : List Job := [\n" + ",\n".join(items) + "]\n\n")
        f.write(f"theorem ok : jobs.all (Job.check (compile {expr}) {upper} {cexpr} {d}) = true := by\n  native_decide\n\n")
        f.write(f"end {ns}.{G}\n")
import re
topterm = re.sub(r"@@(\d+)@@", lambda m: '"0"' if jobs[int(m.group(1))][2] == '0'
                 else f"{gname[grp[int(m.group(1))]]}.h{m.group(1)}", topterm)
with open(os.path.join(outdir, "Main.lean"), 'w') as f:
    f.write("import ManyBoxCert\nimport ManyBoxProbs\n")
    for g in groups: f.write(f"import split.{name}.{gname[g]}\n")
    f.write("open Interval64.KF ManyBox\nset_option profiler true\nset_option profiler.threshold 200\nset_option maxHeartbeats 0\n\n")
    f.write(f"/-! Split certificate `{name}`: {hdr}\n    {len(jobs)} sub-checks in {len(groups)} files (generated by gen_split.py). -/\n\n")
    f.write(f"namespace {ns}\n\n")
    f.write(f"noncomputable def top : Top :=\n{topterm}\n\n")
    envs = ", ".join(f"⟨{LO}, {HI}⟩" for _ in range(d))
    f.write(f"def env0 : List KI := [{envs}]\n\n")
    f.write(f"theorem env0_eq : boxes (V2.cube {d}) = env0 := by decide +kernel\n\n")
    f.write("theorem midsOK : top.midsOK = true := by decide +kernel\n\n")
    f.write("set_option maxRecDepth 100000 in\n")
    f.write("theorem jobs_eq : top.jobs env0 = " + " ++ ".join(f"{gname[g]}.jobs" for g in groups) + " := rfl\n\n")
    f.write(f"theorem all_ok : (top.jobs (boxes (V2.cube {d}))).all (Job.check (compile {expr}) {upper} {cexpr} {d}) = true := by\n")
    f.write("  rw [env0_eq, jobs_eq]\n  simp only [List.all_append, " + ", ".join(f"{gname[g]}.ok" for g in groups) + ", Bool.and_self]\n\n")
    rel = (f"{expr}.denote xs ≤ (({bound} : ℚ) : ℝ)" if ub else f"(({bound} : ℚ) : ℝ) ≤ {expr}.denote xs")
    f.write(f"/-- The claim on the whole cube, from the {len(jobs)} separately compiled sub-checks. -/\n")
    f.write(f"theorem bound (xs : List ℝ) (hxs : RealFP.InBoxes xs (V2.cube {d})) : {rel} :=\n")
    f.write(f"  proveTop_{'le' if ub else 'ge'} {expr} (V2.cube {d}) ({bound}) {d} top midsOK all_ok xs hxs\n\n")
    f.write(f"end {ns}\n\n#print axioms {ns}.bound\n")
print(f"{len(jobs)} jobs, {sum(1 for j in jobs if j[2] != '0')} with certificates, d={d}; wrote {outdir}")
