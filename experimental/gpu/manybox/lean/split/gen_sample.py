#!/usr/bin/env python3
"""Lean file for a *sampled* check (demo (c)): `mb2 sample PROB CERT|DIR K SEED > sample.txt`, then
gen_sample.py sample.txt OUT.lean EXPR BOUND D ge|le "HEADER-COMMENT"
Each sampled leaf box is re-checked by realfp's kernel checker (`decide +kernel`, standard axioms);
the final theorem states the bound on every sampled box (and nothing more)."""
import sys
from fractions import Fraction as F
src, out, expr, bound, d, rel, note = sys.argv[1:8]
d = int(d)
rows = [l.split() for l in open(src) if l.strip() and not l.startswith('#')]
hdr = [l.strip() for l in open(src) if l.startswith('#')]
def q(x): return f"({x.numerator}/{x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"
boxes = []; vol = F(0)
for r in rows:
    l = int(r[0]); c = [int(x) for x in r[1:1 + d]]; b = []
    for j in range(d):
        s = (l + d - 1 - j) // d; h = F(2, 2 ** s)
        b.append((F(-1) + c[j] * h, F(-1) + (c[j] + 1) * h))
    boxes.append(b); vol += F(1, 2 ** l)
prove = "RealFP.prove_ge" if rel == "ge" else "RealFP.prove_le"
stmt = (lambda: f"(({bound} : ℚ) : ℝ) ≤ {expr}.denote xs") if rel == "ge" else (lambda: f"{expr}.denote xs ≤ (({bound} : ℚ) : ℝ)")
with open(out, 'w') as f:
    f.write("import ManyBoxCert\nimport ManyBoxProbs\nopen Interval64.KF ManyBox\n"
            "set_option profiler true\nset_option profiler.threshold 200\nset_option maxHeartbeats 0\nset_option maxRecDepth 20000\n\n")
    f.write("/-! " + note + "\n\n" + "\n".join(hdr) + f"\n{len(boxes)} sampled leaves, total volume fraction {float(vol):.3e} of the cube.\n(generated by split/gen_sample.py) -/\n\n")
    f.write("namespace ManyBox.Sample\n\n")
    f.write("def sampleBoxes : List (List (ℚ × ℚ)) := [\n" + ",\n".join(
        "  [" + ", ".join(f"({q(a)}, {q(b)})" for a, b in bx) + "]" for bx in boxes) + "]\n\n")
    for k, bx in enumerate(boxes):
        bl = "[" + ", ".join(f"({q(a)}, {q(b)})" for a, b in bx) + "]"
        f.write(f"theorem leaf_{k} (xs : List ℝ) (h : RealFP.InBoxes xs {bl}) : {stmt()} :=\n"
                f"  {prove} {expr} {bl} ({bound}) .leaf (by decide +kernel) xs h\n\n")
    f.write(f"/-- The bound holds on every sampled leaf box (kernel-checked). This is all it proves. -/\n"
            f"theorem on_sample : ∀ b : List (ℚ × ℚ), b ∈ sampleBoxes → ∀ xs : List ℝ, RealFP.InBoxes xs b → {stmt()} := by\n"
            f"  intro b hb\n  simp only [sampleBoxes, List.mem_cons, List.not_mem_nil, or_false] at hb\n"
            f"  rcases hb with " + " | ".join("rfl" for _ in boxes) + "\n")
    f.write("  exacts [" + ", ".join(f"leaf_{k}" for k in range(len(boxes))) + "]\n\n")
    f.write("end ManyBox.Sample\n\n#print axioms ManyBox.Sample.on_sample\n")
print(f"{len(boxes)} boxes, volume fraction {float(vol):.3e}")
